def raw(port, *args):
    s = socket.create_connection(("127.0.0.1", port))
    out = b"*%d\r\n" % len(args)
    for a in args:
        a = a if isinstance(a, bytes) else str(a).encode()
        out += b"$%d\r\n%s\r\n" % (len(a), a)
    s.sendall(out)
    return s


def served(port, c, block_args, wake):
    s = raw(port, *block_args)
    time.sleep(0.15)
    c.check(*wake)
    s.settimeout(5)
    data = s.recv(65536)
    s.close()
    return data


